# 2. มาตรฐานการตรวจจับแรงดันไฟฟ้า อาคารเรียนระบบ 3 เฟส (380V)
# =====================================================================
RATED_VOLTAGE = 380.0  # แรงดันไฟมาตรฐานของอาคาร (โวลต์)

VOLTAGE_OVER_TH = RATED_VOLTAGE * 1.10  # 418V (ไฟเกิน: สูงกว่าปกติ 10%)
VOLTAGE_SAG_TH = RATED_VOLTAGE * 0.90  # 342V (ไฟตก/ไฟต่ำ: ต่ำกว่าปกติ 10%)
VOLTAGE_OUTAGE_TH = RATED_VOLTAGE * 0.15  # 57V  (ไฟดับ: แรงดันดิ่งลงจนแทบเป็นศูนย์)


def check_power_status(v, duration_sec=0):
    """
    v: ค่าแรงดันไฟฟ้าที่วัดได้ (โวลต์)
    duration_sec: ระยะเวลาที่เกิดสภาวะนั้นต่อเนื่อง (วินาที)
    """
    # 1. ไฟดับ: แรงดันไฟหาย ดิ่งต่ำกว่า 57V
    if v < VOLTAGE_OUTAGE_TH:
        return "⚫ ไฟดับ (Power Outage)"

    # 2. ไฟเกิน: แรงดันพุ่งสูงเกิน 418V
    elif v > VOLTAGE_OVER_TH:
        return "🔺 ไฟเกิน (Over Voltage)"

    # 3. ไฟตก / ไฟต่ำ: แรงดันร่วงต่ำกว่า 342V (ตัดสินจากระยะเวลา)
    elif v < VOLTAGE_SAG_TH:
        if duration_sec > 60:  # ต่ำค้างนานเกิน 1 นาที (60 วินาที)
            return "🔻 ไฟต่ำ (Undervoltage)"
        else:  # วูบลงสั้นๆ ไม่เกิน 1 นาที
            return "📉 ไฟตก (Voltage Sag)"

    # 4. ไฟปกติ: แรงดันอยู่ในช่วง 342V ถึง 418V
    return "✅ ไฟปกติ (Normal)"


# ลำดับความรุนแรง (เรียงจากอันตรายมากไปน้อย)
SEVERITY_ORDER = [
    "⚫ ไฟดับ (Power Outage)",
    "🔺 ไฟเกิน (Over Voltage)",
    "🔻 ไฟต่ำ (Undervoltage)",
    "📉 ไฟตก (Voltage Sag)",
    "✅ ไฟปกติ (Normal)",
]
SEVERITY_RANK = {status: rank for rank, status in enumerate(SEVERITY_ORDER)}

def worst_status(statuses):
    """เลือกสถานะที่แย่ที่สุดจาก list ของสถานะ 3 เฟส"""
    return min(statuses, key=lambda s: SEVERITY_RANK.get(s, len(SEVERITY_ORDER)))


