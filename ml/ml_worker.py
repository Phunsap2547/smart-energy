TIME_KEYWORDS = ['time', 'timestamp', 'date', 'datetime', 'วันที่', 'เวลา']

def find_time_column(df):
    for col in df.columns:
        if any(kw in col.lower() for kw in TIME_KEYWORDS):
            return col
    return None

MEASURE_KEYWORDS_ORDERED = [
    ('THD_Voltage',   ['harmonic_voltage_distortion', 'thd_voltage', 'voltage_distortion']),
    ('THD_Current',   ['harmonic_current_distortion', 'thd_current', 'current_distortion']),
    ('PowerFactor',   ['power_factor', 'powerfactor']),
    ('ApparentPower', ['apparent_power', 'apparent power']),
    ('ReactivePower', ['reactive_power', 'reactive power']),
    ('RealPower',     ['real_power', 'realpower']),
    ('Voltage',       ['voltage']),
    ('Current',       ['current']),
]

def detect_measurement(filename):
    text = filename.lower()
    for standard_name, keywords in MEASURE_KEYWORDS_ORDERED:
        if any(kw in text for kw in keywords):
            return standard_name
    return None


